"""Report for stage 8 (writes results/replication_2024/README.md).

Applies docs/protocol-2024-replication.md: selection rules E and V, hypotheses R1-R3.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from fuzzshrink.data import rebalance_dates  # noqa: E402

PAPER = {"wealth": 5343.96, "sharpe_eq15": 11.93, "ndx_wealth": 1266.27, "comp_wealth": 1303.87}
BUY, SELL = 0.001, 0.002


def eq15(r: np.ndarray) -> float:
    """The paper's Eq. 15 Sharpe ratio (risk-free rate 0)."""
    return ((1 + r.mean()) ** 12 - 1) / (np.sqrt(np.mean((r - r.mean()) ** 2)) * np.sqrt(12))


def std_sharpe(r: np.ndarray) -> float:
    return r.mean() / r.std(ddof=1) * np.sqrt(12)


def main():
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    df = pd.concat(pd.read_csv(p) for p in sorted((ROOT / "results/runs/replication").glob("seed*.csv")))
    df["year"] = df.month.str[:4]
    keys = ["seed", "pipeline", "C", "criterion"]
    cells = []
    for k, g in df.groupby(keys):
        g = g.sort_values("month")
        r23 = g[g.year == "2023"].net.to_numpy()
        r24 = g[g.year == "2024"].net.to_numpy()
        cells.append(dict(zip(keys, k), w2023=1000 * np.prod(1 + r23), w2024=1000 * np.prod(1 + r24),
                          eq15=eq15(r24), sharpe=std_sharpe(r24), mdd=_mdd(r24),
                          holdings_dec=g[g.month == "2024-12"].holdings.iloc[0]))
    cells = pd.DataFrame(cells)
    seeds = sorted(cells.seed.unique())

    # selection rules
    picks = []
    for (s, p), g in cells.groupby(["seed", "pipeline"]):
        e = g.loc[g.w2024.idxmax()]
        v = g.loc[g.w2023.idxmax()]
        picks.append({"seed": s, "pipeline": p,
                      "E_cell": f"C={e.C}, {e.criterion}", "E_w2024": e.w2024, "E_eq15": e.eq15, "E_sharpe": e.sharpe,
                      "V_cell": f"C={v.C}, {v.criterion}", "V_w2024": v.w2024, "V_eq15": v.eq15, "V_sharpe": v.sharpe,
                      "V_mdd": v.mdd})
    picks = pd.DataFrame(picks)
    piv = lambda col: picks.pivot(index="seed", columns="pipeline", values=col)  # noqa: E731

    # benchmarks for 2024 with the same monthly cost rule
    prices = pd.read_csv(ROOT / "data/raw/base_universe_prices.csv.gz", index_col=0, parse_dates=True)
    prices = prices.loc["2017-01-01":"2024-12-31"].dropna(axis=1, how="any")
    rets = prices.pct_change().iloc[1:]
    qqq = pd.read_csv(ROOT / "data/raw/qqq.csv.gz", index_col=0, parse_dates=True).iloc[:, 0].pct_change()
    dates = rebalance_dates(rets.index, "2024-01-01", "2024-12-31")
    bench = {"QQQ": [], "EW": []}
    for m, d in enumerate(dates):
        end = dates[m + 1] if m + 1 < len(dates) else None
        sl = slice(d, rets.index[rets.index.get_loc(end) - 1] if end is not None else None)
        bench["QQQ"].append(np.prod(1 + qqq.loc[sl]) - 1)
        bench["EW"].append(np.mean(np.prod(1 + rets.loc[sl].to_numpy(), axis=0) - 1))
    bench = {k: (1 - BUY) * (1 + np.array(v)) * (1 - SELL) - 1 for k, v in bench.items()}
    bw = {k: 1000 * np.prod(1 + v) for k, v in bench.items()}

    vB, vP = piv("V_w2024")["B24"], piv("V_w2024")["P24"]
    eB, eP = piv("E_w2024")["B24"], piv("E_w2024")["P24"]
    r1 = bool(vP.mean() > vB.mean() and (vP > vB).sum() >= 3)
    r2 = bool(eP.mean() > eB.mean())
    r3 = bool(vP.mean() > bw["QQQ"])

    grid = (cells.groupby(["pipeline", "criterion", "C"]).w2024.mean().unstack("C").round(0))

    def money(x):
        return f"${x:,.0f}"

    seed_rows = "\n".join(
        f"| {s} | {r.B24_V} | {money(vB[s])} | {r.P24_V} | {money(vP[s])} | {money(eB[s])} | {money(eP[s])} |"
        for s, r in picks.pivot(index="seed", columns="pipeline", values="V_cell")
        .rename(columns={"B24": "B24_V", "P24": "P24_V"}).iterrows())
    grid_md = "\n".join(
        f"| {p} | {c} | " + " | ".join(money(v) for v in row) + " |" for (p, c), row in grid.iterrows())

    text = f"""# Stage 8: the base paper's own 2024 test, rerun

Generated by `scripts/report_replication.py`. Design fixed in advance: `docs/protocol-2024-replication.md`.
85 of the paper's 88 stocks; monthly portfolios Jan–Dec 2024 (2023 is used only by rule V); $1,000 start;
0.1% buy and 0.2% sell every month, as in the paper. {len(seeds)} seeds. **Twelve monthly returns make every
comparison here statistically weak.**

## Hypotheses

| | Hypothesis | Evidence | Verdict |
|---|---|---|---|
| R1 (primary) | Under rule V (chosen on 2023), P24 ends 2024 richer than B24 | P24 {money(vP.mean())} vs B24 {money(vB.mean())}; P24 higher in {(vP > vB).sum()}/{len(seeds)} seeds | {'supported' if r1 else 'not supported'} |
| R2 | Under rule E (best of 21 on 2024), P24 ends richer than B24 | P24 {money(eP.mean())} vs B24 {money(eB.mean())} | {'supported' if r2 else 'not supported'} |
| R3 | Under rule V, P24 beats QQQ | P24 {money(vP.mean())} vs QQQ {money(bw['QQQ'])} | {'supported' if r3 else 'not supported'} |

## Final wealth from $1,000 in 2024 (seed mean)

| | Rule V: chosen on 2023 (honest) | Rule E: best of 21 on 2024 (as the paper did) |
|---|---|---|
| B24, reconstruction of the paper | {money(vB.mean())} | {money(eB.mean())} |
| **P24, ours** | **{money(vP.mean())}** | **{money(eP.mean())}** |
| Paper's published result (its Table 7) | — | {money(PAPER['wealth'])} |
| QQQ (our data, same cost rule) | {money(bw['QQQ'])} | |
| Equal weight, 85 stocks | {money(bw['EW'])} | |
| Paper's published Nasdaq-100 | {money(PAPER['ndx_wealth'])} | |

Sharpe ratios for 2024 (seed mean, standard annualised / the paper's Eq. 15):
B24 rule V {piv('V_sharpe')['B24'].mean():.2f} / {piv('V_eq15')['B24'].mean():.2f};
P24 rule V {piv('V_sharpe')['P24'].mean():.2f} / {piv('V_eq15')['P24'].mean():.2f};
B24 rule E {piv('E_sharpe')['B24'].mean():.2f} / {piv('E_eq15')['B24'].mean():.2f};
P24 rule E {piv('E_sharpe')['P24'].mean():.2f} / {piv('E_eq15')['P24'].mean():.2f}.
The paper reports Eq. 15 = 11.93.

## By seed

| Seed | B24 rule-V choice | B24 rule V | P24 rule-V choice | P24 rule V | B24 rule E | P24 rule E |
|---|---|---|---|---|---|---|
{seed_rows}

## Every cell: 2024 final wealth by clusters and criterion (seed mean; compare with the paper's Table 6)

| Pipeline | Criterion | {' | '.join(f'C = {c}' for c in grid.columns)} |
|---|---|{'---|' * len(grid.columns)}
{grid_md}
"""
    out = ROOT / "results/replication_2024"
    out.mkdir(parents=True, exist_ok=True)
    cells.to_csv(out / "cells.csv", index=False)
    picks.to_csv(out / "picks.csv", index=False)
    (out / "README.md").write_text(text, encoding="utf-8")
    print(text)


def _mdd(r: np.ndarray) -> float:
    w = np.cumprod(1 + r)
    return float((w / np.maximum.accumulate(w) - 1).min())


if __name__ == "__main__":
    main()
