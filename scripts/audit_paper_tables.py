"""Stage 9, Q1 and F1: audit the base paper's published tables and its forecast-accuracy claim.

Q1 uses only numbers printed in the paper (Tables 7, 8, 10; Eq. 14-15) plus 2024 index data.
F1 computes random-walk price MAPE for the 85 stocks in 2024 (protocol section 3).
Usage:
    python scripts/audit_paper_tables.py
Writes results/replication_paper/audit.md and audit.csv.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
import yfinance as yf

ROOT = Path(__file__).resolve().parents[1]

# (row, reported annual return %, reported annual risk %, reported Sharpe, final wealth $) from the paper
PUBLISHED = [
    ("Proposed model, max return (Tables 7, 10)", 565.89, 47.42, 11.93, 5343.96),
    ("Proposed model, max Sharpe (Table 7)", 388.45, 43.42, 8.95, 3958.19),
    ("Proposed model, min risk (Table 7)", 178.26, 26.79, 6.65, 2344.57),
    ("Improved K-means (Table 8)", 133.40, 37.27, 3.58, 1906.10),
    ("Fuzzy C-means (Table 8)", 165.02, 35.24, 4.68, 2179.82),
    ("Alternative model 1, random selection (Table 10)", 189.0, 31.96, 6.2, 2369.31),
    ("Alternative model 2, historical means (Table 10)", 23.61, 39.94, 0.59, 999.51),
    ("Alternative model 3, equal weights (Table 10)", 88.14, 32.13, 2.74, 1558.83),
    ("Nasdaq Composite (Table 7)", 1.37, 3.93, 0.35, 1303.87),
    ("Nasdaq-100 (Table 7)", 1.23, 3.97, 0.31, 1266.27),
]
PAPER_MAPE = 1.67


def main():
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    out = ROOT / "results/replication_paper"
    out.mkdir(parents=True, exist_ok=True)

    rows = []
    for name, ret, risk, sr, wealth in PUBLISHED:
        implied = 100 * (wealth / 1000 - 1)
        m = (1 + ret / 100) ** (1 / 12) - 1  # monthly arithmetic mean implied by Eq. 15's numerator
        s = risk / 100 / np.sqrt(12)  # monthly sd implied by Eq. 15's denominator
        rows.append({"row": name, "reported_return": ret, "wealth_implied_return": implied,
                     "reported_sharpe": sr, "return_over_risk": ret / risk,
                     "standard_sharpe_from_reported_moments": 12 * m / (s * np.sqrt(12))})
    audit = pd.DataFrame(rows)

    idx = yf.download(["^NDX", "^IXIC"], start="2023-12-01", end="2025-01-03", auto_adjust=True,
                      progress=False)["Close"]
    mo = idx.resample("ME").last().pct_change().loc["2024-01":"2024-12"]
    bench = []
    for c, label in (("^IXIC", "Nasdaq Composite"), ("^NDX", "Nasdaq-100")):
        r = mo[c]
        net = 0.999 * (1 + r) * 0.998 - 1
        bench.append({"index": label, "monthly_mean_%": 100 * r.mean(), "monthly_sd_%": 100 * r.std(ddof=0),
                      "price_return_2024_%": 100 * ((1 + r).prod() - 1),
                      "wealth_with_paper_costs": 1000 * (1 + net).prod(),
                      "eq15_sharpe": ((1 + r.mean()) ** 12 - 1) / (r.std(ddof=0) * np.sqrt(12)),
                      "standard_sharpe": r.mean() / r.std(ddof=1) * np.sqrt(12)})
    bench = pd.DataFrame(bench)

    # F1: random-walk MAPE for the 85 stocks in 2024 (adjusted closes)
    prices = pd.read_csv(ROOT / "data/raw/base_universe_prices.csv.gz", index_col=0, parse_dates=True)
    prices = prices.loc["2017-01-01":"2024-12-31"].dropna(axis=1, how="any")
    p24 = prices.loc["2024-01-01":]
    prev = prices.shift(1).loc["2024-01-01":]
    mape_h1 = 100 * float((abs(p24 - prev) / p24).stack().mean())
    month_rows = []
    for _, g in p24.groupby(p24.index.to_period("M")):
        p0 = prices.loc[: g.index[0] - pd.Timedelta(days=1)].iloc[-1]  # last price known at month start
        month_rows.append((abs(g - p0) / g).stack())
    mape_month = 100 * float(pd.concat(month_rows).mean())
    amzn_h1 = 100 * float((abs(p24["AMZN"] - prev["AMZN"]) / p24["AMZN"]).mean())

    audit.to_csv(out / "audit.csv", index=False)
    bench.to_csv(out / "index_2024.csv", index=False)
    pd.DataFrame([{"paper_reported_mape": PAPER_MAPE, "random_walk_mape_h1": mape_h1,
                   "random_walk_mape_month_ahead": mape_month, "random_walk_mape_h1_AMZN": amzn_h1,
                   "paper_reported_mape_AMZN": 1.33}]).to_csv(out / "forecast_baseline.csv", index=False)

    def fmt(df, f="{:.2f}"):
        cols = list(df.columns)
        lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
        for r in df.itertuples(index=False):
            lines.append("| " + " | ".join(f.format(v) if isinstance(v, float) else str(v) for v in r) + " |")
        return "\n".join(lines)

    text = f"""# Audit of the base paper's published figures (Q1) and forecast baseline (F1)

Generated by `scripts/audit_paper_tables.py`. Q1 uses only numbers printed in Dastkhan, Mosaffa and
Fabozzi (2026), Tables 7, 8 and 10, and their Eq. 14–15. Index data: Yahoo Finance (^IXIC, ^NDX).

## Reported annual return against the return implied by the reported final wealth ($1,000 start)

{fmt(audit)}

Every "reported Sharpe" equals reported return ÷ reported risk, i.e. Eq. 15. Eq. 15's numerator
compounds the *arithmetic* mean monthly return, (1 + mean)^12 − 1, which exceeds the realised
return whenever returns vary; hence reported returns above the wealth-implied ones.
The benchmark rows report 1.37% and 1.23% "annual" returns while their own wealth figures imply
+30.4% and +26.6%.

## The benchmarks in 2024, recomputed

{fmt(bench)}

Applying the paper's own Eq. 15 to the actual 2024 index returns gives Sharpe ratios of
{bench.eq15_sharpe.iloc[0]:.2f} and {bench.eq15_sharpe.iloc[1]:.2f}, not 0.35 and 0.31.

## F1: is a 1.67% price MAPE evidence of forecasting skill?

| Forecast of daily prices, 85 stocks, 2024 | MAPE |
|---|---|
| Paper's LSTM (reported, Section 4.1) | {PAPER_MAPE:.2f}% |
| Random walk, 1 day ahead (tomorrow's price = today's) | {mape_h1:.2f}% |
| Random walk, whole next month from the month-start price | {mape_month:.2f}% |
| Paper's LSTM for AMZN (reported) | 1.33% |
| Random walk, 1 day ahead, AMZN | {amzn_h1:.2f}% |

Reading fixed in the protocol: the reported accuracy is evidence of skill only if it beats the
1-day random walk. {"It does not." if mape_h1 <= PAPER_MAPE else "It does."}
"""
    (out / "audit.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
