"""Data-quality report for the downloaded prices (writes results/data/README.md).

Usage:
    python scripts/data_report.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from fuzzshrink.data import load_prices, prices_to_returns, rebalance_dates, window_slices  # noqa: E402


def main():
    overrides = pd.read_csv("data/universe/listing_overrides.csv")
    prices = load_prices("data/raw/prices.csv.gz", overrides="data/universe/listing_overrides.csv")
    universe = pd.read_csv("data/universe/nasdaq100_constituents.csv")
    rets = prices_to_returns(prices)
    out = Path("results/data")
    out.mkdir(parents=True, exist_ok=True)

    first = prices.apply(lambda s: s.first_valid_index())
    life = {t: rets.loc[first[t]:, t].iloc[1:] for t in rets.columns}
    gaps = pd.Series({t: int(s.isna().sum()) for t, s in life.items()})
    extreme = rets.abs().stack()
    extreme = extreme[extreme > 0.4].sort_values(ascending=False)

    dates = rebalance_dates(rets.index, "2017-01-01", "2024-12-31")
    sizes = {}
    for T in (126, 252, 504):
        sizes[T] = pd.Series({d: est.shape[1] for d, est, _ in window_slices(rets, dates, T)})
    size_tab = pd.DataFrame(sizes)
    by_year = size_tab.groupby(size_tab.index.year).agg(["min", "max"])

    corr = []
    for d, est, _ in window_slices(rets, dates, 252):
        R = np.corrcoef(est.to_numpy(), rowvar=False)
        corr.append({"date": d, "mean_corr": R[np.triu_indices_from(R, 1)].mean()})
    corr = pd.DataFrame(corr).set_index("date").mean_corr

    missing = sorted(set(universe.ticker) - set(prices.columns))
    sectors = universe[universe.ticker.isin(prices.columns)].sector.value_counts()

    lines = [
        "# Data report",
        "",
        "Generated by `scripts/data_report.py` from `data/raw/prices.csv.gz` (not committed;",
        "rebuild with `python scripts/download_data.py`).",
        "",
        "## Universe",
        "",
        f"- Constituents listed on Wikipedia on {universe.fetched_on.iloc[0]}: {len(universe)}.",
        f"- With any price data in {prices.index.min().date()} to {prices.index.max().date()}: {prices.shape[1]}.",
        f"- No data in the period (listed later): {', '.join(missing) if missing else 'none'}.",
        f"- Trading days: {prices.shape[0]}.",
        "",
        "Listing overrides (`data/universe/listing_overrides.csv`): history before these dates",
        "belongs to a different security and is dropped.",
        "",
        "| Ticker | Valid from | Reason |",
        "|---|---|---|",
        *[f"| {o.ticker} | {o.valid_from} | {o.reason} |" for o in overrides.itertuples()],
        "",
        "Industry mix of the tickers with data (ICB industry, from Wikipedia):",
        "",
        "| Industry | Tickers |",
        "|---|---|",
        *[f"| {k} | {v} |" for k, v in sectors.items()],
        "",
        "## Assets per rebalance window",
        "",
        "Assets with complete returns over the estimation window and the holding period,",
        "by year of the rebalance date (minimum and maximum over the year's 12 rebalances):",
        "",
        "| Year | T = 126 | T = 252 | T = 504 |",
        "|---|---|---|---|",
        *[f"| {y} | {r[(126, 'min')]}–{r[(126, 'max')]} | {r[(252, 'min')]}–{r[(252, 'max')]} "
          f"| {r[(504, 'min')]}–{r[(504, 'max')]} |" for y, r in by_year.iterrows()],
        "",
        f"T / N at T = 252 ranges from {252 / size_tab[252].max():.2f} to {252 / size_tab[252].min():.2f}, "
        "the regime where shrinkage matters.",
        "",
        "## Quality checks",
        "",
        f"- Missing daily returns inside a ticker's trading life: {int(gaps.sum())} in total "
        f"({int((gaps > 0).sum())} tickers affected).",
        f"- Daily moves larger than 40% in absolute value: {len(extreme)}.",
        "",
    ]
    if len(extreme):
        lines += ["| Date | Ticker | Return |", "|---|---|---|"]
        lines += [f"| {d.date()} | {t} | {v:+.1%} |"
                  for (d, t), v in rets.stack().loc[extreme.index[:15]].items()]
        lines += ["", "These match known events (earnings gaps, the March 2020 crash) rather than",
                  "data errors, so they are kept; adjusted prices already account for splits.", ""]
    lines += [
        "## Average pairwise correlation (252-day window, by year)",
        "",
        "| Year | Mean correlation |",
        "|---|---|",
        *[f"| {y} | {v:.3f} |" for y, v in corr.groupby(corr.index.year).mean().items()],
        "",
    ]
    (out / "README.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
